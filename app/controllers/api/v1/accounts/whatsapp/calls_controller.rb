class Api::V1::Accounts::Whatsapp::CallsController < Api::V1::Accounts::BaseController
  # Authorize using Conversation policy only for actions that set @conversation via before_action
  before_action -> { check_authorization(Conversation) }, only: [:create, :history, :terminate]
  before_action :set_conversation, only: [:create, :history, :terminate]
  before_action :set_inbox, only: [:create, :terminate, :request_permission, :check_permission]
  before_action :validate_calling_enabled, only: [:create, :request_permission]

  # POST /api/v1/accounts/:account_id/whatsapp/calls
  # Initiate an outbound call to a contact
  def create
    result = Whatsapp::Calling::OutboundCallService.initiate_call(
      account: Current.account,
      inbox: @inbox,
      contact: @conversation.contact,
      user: Current.user,
      conversation: @conversation
    )

    render json: {
      message: 'Call initiated successfully',
      call_id: result[:call_id],
      conversation_id: @conversation.display_id,
      status: result[:status]
    }, status: :ok
  rescue Whatsapp::Calling::OutboundCallService::PermissionError => e
    render json: {
      error: e.message,
      error_code: 'PERMISSION_DENIED'
    }, status: :forbidden
  rescue Whatsapp::Calling::OutboundCallService::LimitError => e
    render json: {
      error: e.message,
      error_code: 'LIMIT_EXCEEDED'
    }, status: :too_many_requests
  rescue Whatsapp::Calling::OutboundCallService::CallInitiationError => e
    render json: {
      error: e.message,
      error_code: 'INITIATION_FAILED'
    }, status: :unprocessable_entity
  rescue Whatsapp::Calling::ApiAdapter::NetworkError
    render json: {
      error: 'WhatsApp service temporarily unavailable',
      error_code: 'WHATSAPP_API_UNAVAILABLE',
      retry_after: 30
    }, status: :service_unavailable
  rescue Whatsapp::Calling::ApiAdapter::RateLimitError => e
    render json: {
      error: e.message,
      error_code: 'RATE_LIMIT_EXCEEDED',
      retry_after: e.retry_after
    }, status: :too_many_requests
  end

  # POST /api/v1/accounts/:account_id/whatsapp/calls/:call_id/accept
  # Accept an incoming call
  def accept
    call_id = params[:call_id]

    if call_id.blank?
      return render json: {
        error: 'Call ID is required',
        error_code: 'MISSING_CALL_ID'
      }, status: :bad_request
    end

    # Find the WhatsappCall record
    whatsapp_call = WhatsappCall.find_by(call_id: call_id, account: Current.account)

    unless whatsapp_call
      return render json: {
        error: 'Call not found',
        error_code: 'CALL_NOT_FOUND'
      }, status: :not_found
    end

    # Verify it's an inbound call
    unless whatsapp_call.direction == 'inbound'
      return render json: {
        error: 'Can only accept inbound calls',
        error_code: 'INVALID_DIRECTION'
      }, status: :unprocessable_entity
    end

    # Accept the call - send accept to WhatsApp API
    conversation = whatsapp_call.conversation
    inbox = conversation.inbox
    channel = inbox.channel

    # Get SDP answer from frontend (generated by WebRTC)
    sdp_answer = params[:sdp_answer]

    if sdp_answer.blank?
      return render json: {
        error: 'SDP answer is required',
        error_code: 'MISSING_SDP_ANSWER'
      }, status: :unprocessable_entity
    end

    Rails.logger.info "[WHATSAPP_CALLS] Accepting call with SDP answer from frontend (length: #{sdp_answer.length})"

    # Call WhatsApp API to accept the call
    api_adapter = Whatsapp::Calling::ApiAdapter.new(channel)
    accept_result = api_adapter.accept_call(call_id: call_id, sdp_answer: sdp_answer)

    if accept_result[:success]
      # Update WhatsappCall status
      whatsapp_call.update!(
        status: 'connected',
        connected_at: Time.current,
        accepted_by_user: Current.user
      )

      # Update conversation
      conversation.update!(
        additional_attributes: conversation.additional_attributes.merge(
          'call_status' => 'connected',
          'accepted_at' => Time.current.to_i,
          'accepted_by' => Current.user.id
        )
      )

      # Broadcast event
      ActionCable.server.broadcast(
        "account_#{Current.account.id}",
        {
          event: 'whatsapp_call_accepted',
          data: {
            account_id: Current.account.id,
            call_id: call_id,
            conversation_id: conversation.display_id,
            accepted_by: Current.user.name
          }
        }
      )

      Rails.logger.info "[WHATSAPP_CALLS] Call #{call_id} accepted successfully by #{Current.user.name}"

      render json: {
        message: 'Call accepted successfully',
        call_id: call_id,
        conversation_id: conversation.display_id,
        sdp_answer: accept_result[:sdp_answer]
      }, status: :ok
    else
      Rails.logger.error "[WHATSAPP_CALLS] WhatsApp API accept failed: #{accept_result[:error]}"
      render json: {
        error: 'Failed to accept call with WhatsApp',
        error_code: 'WHATSAPP_ACCEPT_FAILED',
        details: accept_result[:error]
      }, status: :unprocessable_entity
    end
  rescue StandardError => e
    Rails.logger.error "[WHATSAPP_CALLS] Accept failed: #{e.class} - #{e.message}"
    render json: {
      error: 'Failed to accept call',
      error_code: 'ACCEPT_ERROR'
    }, status: :unprocessable_entity
  end

  # POST /api/v1/accounts/:account_id/whatsapp/calls/answer
  # Answer an incoming call (call_id in body, not URL)
  def answer
    call_id = params[:call_id]

    if call_id.blank?
      return render json: {
        error: 'Call ID is required',
        error_code: 'MISSING_CALL_ID'
      }, status: :bad_request
    end

    # Find the WhatsappCall record
    whatsapp_call = WhatsappCall.find_by(call_id: call_id, account: Current.account)

    unless whatsapp_call
      return render json: {
        error: 'Call not found',
        error_code: 'CALL_NOT_FOUND'
      }, status: :not_found
    end

    # Verify it's an inbound call
    unless whatsapp_call.direction == 'inbound'
      return render json: {
        error: 'Can only answer inbound calls',
        error_code: 'INVALID_DIRECTION'
      }, status: :unprocessable_entity
    end

    # Answer the call - send answer to WhatsApp API
    conversation = whatsapp_call.conversation
    inbox = conversation.inbox
    channel = inbox.channel

    # Auto-assign conversation to accepting agent if unassigned
    if conversation.assignee.blank?
      Conversations::AssignmentService.new(
        conversation: conversation,
        assignee_id: Current.user.id
      ).perform
      Rails.logger.info "[WHATSAPP_CALLS] Auto-assigned conversation #{conversation.display_id} to user #{Current.user.id}"
    end

    # Get SDP answer from frontend (generated by WebRTC)
    sdp_answer = params[:sdp_answer]

    if sdp_answer.blank?
      return render json: {
        error: 'SDP answer is required',
        error_code: 'MISSING_SDP_ANSWER'
      }, status: :unprocessable_entity
    end

    Rails.logger.info "[WHATSAPP_CALLS] Answering call #{call_id} with SDP answer from frontend (length: #{sdp_answer.length})"

    begin
      # Call WhatsApp API to accept the call
      api_adapter = Whatsapp::Calling::ApiAdapter.new(channel)
      api_response = api_adapter.accept_call(call_id: call_id, sdp_answer: sdp_answer)

      Rails.logger.info "[WHATSAPP_CALLS] WhatsApp API accept successful: #{api_response.inspect}"

      # Update WhatsappCall status
      whatsapp_call.update!(
        status: 'connected',
        connected_at: Time.current,
        accepted_by_user: Current.user
      )

      # Update conversation
      conversation.update!(
        additional_attributes: conversation.additional_attributes.merge(
          'call_status' => 'connected',
          'accepted_at' => Time.current.to_i,
          'accepted_by' => Current.user.id
        )
      )

      # Broadcast event
      ActionCable.server.broadcast(
        "account_#{Current.account.id}",
        {
          event: 'whatsapp_call_accepted',
          data: {
            account_id: Current.account.id,
            call_id: call_id,
            conversation_id: conversation.display_id,
            accepted_by: Current.user.name
          }
        }
      )

      render json: {
        success: true,
        call_id: call_id,
        status: 'connected'
      }
    rescue Whatsapp::Calling::ApiAdapter::ApiError => e
      Rails.logger.error "[WHATSAPP_CALLS] WhatsApp API accept failed: #{e.message}"
      render json: {
        error: 'Failed to answer call with WhatsApp',
        error_code: 'WHATSAPP_ANSWER_FAILED',
        details: e.message
      }, status: :unprocessable_entity
    rescue StandardError => e
      Rails.logger.error "[WHATSAPP_CALLS] Answer failed: #{e.class} - #{e.message}"
      Rails.logger.error e.backtrace.join("\n")
      render json: {
        error: 'Failed to answer call',
        error_code: 'ANSWER_ERROR',
        details: e.message
      }, status: :unprocessable_entity
    end
  end

  # POST /api/v1/accounts/:account_id/whatsapp/calls/:call_id/reject
  # Reject an incoming call
  def reject
    call_id = params[:call_id]
    reason = params[:reason] || 'declined'

    if call_id.blank?
      return render json: {
        error: 'Call ID is required',
        error_code: 'MISSING_CALL_ID'
      }, status: :bad_request
    end

    # Find the WhatsappCall record
    whatsapp_call = WhatsappCall.find_by(call_id: call_id, account: Current.account)

    unless whatsapp_call
      return render json: {
        error: 'Call not found',
        error_code: 'CALL_NOT_FOUND'
      }, status: :not_found
    end

    # Verify it's an inbound call
    unless whatsapp_call.direction == 'inbound'
      return render json: {
        error: 'Can only reject inbound calls',
        error_code: 'INVALID_DIRECTION'
      }, status: :unprocessable_entity
    end

    # Reject the call
    conversation = whatsapp_call.conversation
    inbox = conversation.inbox

    # Call WhatsApp API to reject
    api_adapter = Whatsapp::Calling::ApiAdapter.new(inbox.channel)
    api_adapter.reject_call(call_id: call_id)

    # Update status regardless of API result (best effort)
    # Update WhatsappCall status
    whatsapp_call.update!(
      status: 'rejected',
      ended_at: Time.current,
      rejection_reason: reason
    )

    # Update conversation
    conversation.update!(
      additional_attributes: conversation.additional_attributes.merge(
        'call_status' => 'rejected',
        'rejected_at' => Time.current.to_i,
        'rejected_by' => Current.user.id,
        'rejection_reason' => reason
      )
    )

    # Create rejected message
    builder = Whatsapp::Calling::CallMessageBuilder.new(
      conversation: conversation,
      whatsapp_call: whatsapp_call
    )
    builder.create_failed_message(reason: 'rejected')

    # Broadcast event
    ActionCable.server.broadcast(
      "account_#{Current.account.id}",
      {
        event: 'whatsapp_call_rejected',
        call_id: call_id,
        conversation_id: conversation.display_id,
        rejected_by: Current.user.name,
        reason: reason
      }
    )

    render json: {
      message: 'Call rejected successfully',
      call_id: call_id
    }, status: :ok
  rescue StandardError => e
    Rails.logger.error "[WHATSAPP_CALLS] Reject failed: #{e.class} - #{e.message}"
    render json: {
      error: 'Failed to reject call',
      error_code: 'REJECT_ERROR'
    }, status: :unprocessable_entity
  end

  # POST /api/v1/accounts/:account_id/whatsapp/calls/:call_id/terminate
  # Terminate an active call
  def terminate
    call_id = params[:call_id]
    conversation_id = params[:conversation_id]

    Rails.logger.info "[WHATSAPP_CALLS] Terminate request - call_id: #{call_id}, conversation: #{conversation_id}"

    if call_id.blank?
      Rails.logger.warn '[WHATSAPP_CALLS] No call_id provided in terminate request'
      return render json: {
        error: 'Call ID is required',
        error_code: 'MISSING_CALL_ID'
      }, status: :bad_request
    end

    # Find the WhatsappCall record to check if already terminated
    whatsapp_call = WhatsappCall.find_by(call_id: call_id, account: Current.account)

    if whatsapp_call && whatsapp_call.status == 'completed'
      Rails.logger.info "[WHATSAPP_CALLS] Call #{call_id} already terminated, skipping"
      return render json: { message: 'Call already terminated' }, status: :ok
    end

    Rails.logger.info "[WHATSAPP_CALLS] Terminating call #{call_id} on WhatsApp API"

    api_adapter = Whatsapp::Calling::ApiAdapter.new(@inbox.channel)
    api_adapter.terminate_call(call_id: call_id)

    Rails.logger.info "[WHATSAPP_CALLS] Call #{call_id} terminated successfully on WhatsApp"

    render json: { message: 'Call terminated successfully' }, status: :ok
  rescue Whatsapp::Calling::ApiAdapter::NetworkError => e
    Rails.logger.error "[WHATSAPP_CALLS] Network error: #{e.message}"
    render json: {
      error: 'WhatsApp service temporarily unavailable',
      error_code: 'WHATSAPP_API_UNAVAILABLE',
      retry_after: 30
    }, status: :service_unavailable
  rescue Whatsapp::Calling::ApiAdapter::TimeoutError => e
    Rails.logger.error "[WHATSAPP_CALLS] Timeout error: #{e.message}"
    render json: {
      error: 'Request timed out',
      error_code: 'TIMEOUT',
      retry_after: 10
    }, status: :gateway_timeout
  rescue StandardError => e
    Rails.logger.error "[WHATSAPP_CALLS] Terminate failed: #{e.class} - #{e.message}"
    render json: {
      error: 'Failed to terminate call',
      error_code: 'TERMINATION_FAILED'
    }, status: :unprocessable_entity
  end

  # POST /api/v1/accounts/:account_id/whatsapp/calls/permissions
  # Request permission from a contact to make calls
  def request_permission
    contact = Current.account.contacts.find_by(id: params[:contact_id])

    return render json: { error: 'Contact not found' }, status: :not_found unless contact

    permission = Whatsapp::Calling::PermissionRequestService.request_permission(
      account: Current.account,
      inbox: @inbox,
      contact: contact,
      user: Current.user
    )

    render json: {
      message: 'Permission request sent successfully',
      permission: permission_json(permission)
    }, status: :ok
  rescue Whatsapp::Calling::PermissionRequestService::AlreadyRequestedError => e
    render json: { error: e.message }, status: :conflict
  rescue Whatsapp::Calling::PermissionRequestService::PermissionError => e
    render json: { error: e.message }, status: :unprocessable_entity
  end

  # GET /api/v1/accounts/:account_id/whatsapp/calls/permissions
  # Get permission status for a contact
  def check_permission
    contact = Current.account.contacts.find_by(id: params[:contact_id])

    return render json: { error: 'Contact not found' }, status: :not_found unless contact

    permission = Whatsapp::CallPermission.find_by(
      account: Current.account,
      inbox: @inbox,
      contact: contact,
      phone_number_id: @channel.phone_number_id
    )

    if permission
      render json: { permission: permission_json(permission) }, status: :ok
    else
      render json: {
        permission: {
          status: 'not_requested',
          can_request: true,
          remaining_calls: 0
        }
      }, status: :ok
    end
  end

  # GET /api/v1/accounts/:account_id/whatsapp/calls/history
  # Get call history for a conversation
  def history
    page = params[:page] || 1
    per_page = params[:per_page] || 20

    calls = extract_call_history(@conversation)
    paginated_calls = Kaminari.paginate_array(calls).page(page).per(per_page)

    render json: {
      calls: paginated_calls,
      meta: {
        current_page: paginated_calls.current_page,
        total_pages: paginated_calls.total_pages,
        total_count: calls.length,
        has_more: paginated_calls.current_page < paginated_calls.total_pages
      }
    }, status: :ok
  end

  # GET /api/v1/accounts/:account_id/whatsapp/calls/analytics
  # Get call analytics for an inbox or account
  def analytics
    start_date = params[:start_date] ? Time.zone.parse(params[:start_date]) : 30.days.ago
    end_date = params[:end_date] ? Time.zone.parse(params[:end_date]) : Time.zone.now
    inbox_id = params[:inbox_id]

    # Use WhatsappCall model for better performance
    calls = Current.account.whatsapp_calls
                   .for_date_range(start_date, end_date)

    calls = calls.for_inbox(inbox_id) if inbox_id.present?

    analytics_data = calculate_analytics_from_calls(calls)

    render json: { analytics: analytics_data }, status: :ok
  end

  # POST /api/v1/accounts/:account_id/whatsapp/calls/setup_webrtc
  def setup_webrtc
    Rails.logger.info "[WHATSAPP_CALLS] setup_webrtc - P2P mode with WhatsApp, params: conversation_id=#{params[:conversation_id]}, call_id=#{params[:call_id]}"
    conversation = find_conversation_for_webrtc(params[:conversation_id], params[:call_id])
    return render json: { error: 'Conversation not found' }, status: :not_found unless conversation

    authorize conversation, :show?

    call_id_param = params[:call_id]
    sdp_offer = params[:sdp_offer]

    if sdp_offer.present?
      Rails.logger.info '[WHATSAPP_CALLS] setup_webrtc - Initiating P2P call with WhatsApp'

      setup_result = conversation.with_lock do
        persist_browser_sdp_offer(conversation, sdp_offer, call_id_param)

        Whatsapp::Calling::WebrtcSetupService.new(
          account: Current.account,
          inbox: conversation.inbox,
          conversation: conversation,
          call_id: call_id_param,
          sdp_offer: sdp_offer
        ).perform
      end

      Rails.logger.info "[WHATSAPP_CALLS] setup_webrtc - Result: success=#{setup_result[:success]}"

      unless setup_result[:success]
        # Update initiated message to show error when WhatsApp API fails
        handle_webrtc_setup_error(conversation, call_id_param, setup_result[:error])
        return render json: { error: setup_result[:error] }, status: :unprocessable_entity
      end

      call_id = setup_result[:call_id]
    end

    # Get WhatsApp SDP answer
    whatsapp_call = conversation.additional_attributes&.dig('whatsapp_call') || {}
    sdp_answer = whatsapp_call['whatsapp_sdp_answer'] || whatsapp_call['sdp_answer']
    call_id ||= whatsapp_call['id'] || call_id_param

    if sdp_answer.present?
      Rails.logger.info '[WHATSAPP_CALLS] setup_webrtc - Returning WhatsApp SDP answer'
      render json: { callId: call_id, sdpAnswer: sdp_answer }, status: :ok
    else
      Rails.logger.info '[WHATSAPP_CALLS] setup_webrtc - SDP answer pending'
      render json: { callId: call_id, message: 'SDP answer pending' }, status: :accepted
    end
  rescue StandardError => e
    Rails.logger.error "[WHATSAPP_CALLS] setup_webrtc failed: #{e.message}"
    Rails.logger.error e.backtrace.join("\n")
    render json: { error: e.message }, status: :unprocessable_entity
  end

