  private

  def set_conversation
    @conversation = Current.account.conversations.find_by(id: params[:conversation_id])
    return render json: { error: 'Conversation not found' }, status: :not_found unless @conversation
  end

  def set_inbox
    inbox_id = @conversation&.inbox_id || params[:inbox_id]
    @inbox = Current.account.inboxes.find_by(id: inbox_id)
    return render json: { error: 'Inbox not found' }, status: :not_found unless @inbox

    return if @inbox.channel_type == 'Channel::Whatsapp'

    render json: { error: 'Not a WhatsApp inbox' }, status: :bad_request
  end

  def validate_calling_enabled
    return if @inbox.channel.calling_enabled?

    render json: { error: 'Calling is not enabled for this WhatsApp channel' }, status: :forbidden
  end

  def permission_json(permission)
    {
      id: permission.id,
      status: permission.status,
      granted: permission.granted?,
      can_make_call: permission.can_make_call?,
      remaining_calls: permission.remaining_calls,
      expires_at: permission.expires_at,
      granted_at: permission.granted_at,
      requested_at: permission.requested_at
    }
  end

  def extract_call_history(conversation)
    # Extract calls from messages with content_type 'call'
    # Preload contact to avoid N+1
    call_messages = conversation.messages
                                .includes(:sender)
                                .where(content_type: 'call')
                                .order(created_at: :desc)

    # Cache contact info to avoid repeated lookups
    contact_name = conversation.contact.name
    contact_number = conversation.contact.phone_number

    call_messages.map do |message|
      attrs = message.content_attributes || {}
      {
        id: attrs['call_id'],
        direction: attrs['direction'],
        status: attrs['status'],
        duration: attrs['duration'],
        initiated_at: attrs['initiated_at'],
        answered_at: attrs['answered_at'],
        ended_at: attrs['ended_at'],
        end_reason: attrs['end_reason'],
        recording_url: attrs['recording_url'],
        quality_metrics: attrs['quality_metrics'],
        contact_name: contact_name,
        contact_number: contact_number,
        created_at: message.created_at
      }
    end
  end

  def calculate_analytics_from_calls(calls)
    # Use ActiveRecord aggregations for better performance
    total_calls = calls.count
    inbound_calls = calls.direction_inbound.count
    outbound_calls = calls.direction_outbound.count
    completed_calls = calls.successful.count
    failed_calls = calls.where(status: %w[failed rejected timeout cancelled]).count
    total_duration = calls.successful.sum(:duration_seconds)

    {
      total_calls: total_calls,
      inbound_calls: inbound_calls,
      outbound_calls: outbound_calls,
      completed_calls: completed_calls,
      failed_calls: failed_calls,
      success_rate: total_calls.positive? ? ((completed_calls.to_f / total_calls) * 100).round(2) : 0,
      average_duration: completed_calls.positive? ? (total_duration.to_f / completed_calls).round(2) : 0,
      total_duration: total_duration
    }
  end

  def check_or_create_permission(contact)
    Whatsapp::CallPermission.find_or_create_by!(
      account: Current.account,
      inbox: @inbox,
      contact: contact,
      phone_number_id: @channel.phone_number_id
    ) do |permission|
      permission.permission_status = 'pending'
    end
  end

  def find_conversation_for_webrtc(conversation_id, call_id)
    if conversation_id.present?
      conversation = Current.account.conversations.find_by(id: conversation_id)
      return conversation if conversation
    end

    return nil if call_id.blank?

    Current.account.conversations.find_by(identifier: call_id) ||
      Current.account.conversations.where("additional_attributes -> 'whatsapp_call' ->> 'id' = ?", call_id).first
  end

  def persist_browser_sdp_offer(conversation, sdp_offer, call_id)
    return unless conversation

    attrs = (conversation.additional_attributes || {}).deep_dup
    whatsapp_call = attrs['whatsapp_call'] || {}
    updated = false

    if sdp_offer.present?
      whatsapp_call['browser_sdp_offer'] = sdp_offer
      updated = true
    end

    if call_id.present?
      whatsapp_call['id'] = call_id
      updated = true
    end

    return unless updated

    attrs['whatsapp_call'] = whatsapp_call
    conversation.update!(additional_attributes: attrs)
  rescue StandardError => e
    Rails.logger.error "[WHATSAPP_CALLS] Failed to persist browser offer: #{e.message}"
  end

  def save_recording_file(whatsapp_call, recording_file)
    # Create recordings directory if it doesn't exist
    recordings_dir = Rails.root.join('storage/call_recordings')
    FileUtils.mkdir_p(recordings_dir)

    # Generate unique filename
    timestamp = Time.current.strftime('%Y%m%d_%H%M%S')
    filename = "call_#{whatsapp_call.call_id}_#{timestamp}.webm"
    file_path = recordings_dir.join(filename)

    # Save file
    File.binwrite(file_path, recording_file.read)

    Rails.logger.info "[WHATSAPP_CALLS] Recording saved to: #{file_path}"

    # Return relative path for storage
    "call_recordings/#{filename}"
  end

  def create_recording_message(whatsapp_call, recording_path)
    conversation = whatsapp_call.conversation
    return unless conversation

    # Create message with recording attachment
    message = conversation.messages.create!(
      account: whatsapp_call.account,
      inbox: whatsapp_call.inbox,
      message_type: :activity,
      content: "Grabación de llamada (#{format_duration(whatsapp_call.duration)})",
      sender: nil
    )

    # Attach recording file
    full_path = Rails.root.join('storage', recording_path)
    if File.exist?(full_path)
      message.attachments.create!(
        account: whatsapp_call.account,
        file: File.open(full_path),
        file_type: :audio
      )
      Rails.logger.info "[WHATSAPP_CALLS] Recording message created: message_id=#{message.id}"
    else
      Rails.logger.error "[WHATSAPP_CALLS] Recording file not found: #{full_path}"
    end
  rescue StandardError => e
    Rails.logger.error "[WHATSAPP_CALLS] Failed to create recording message: #{e.message}"
  end

  def process_recording_upload(call_id, recording_file, duration_param = nil)
    Rails.logger.info "[WHATSAPP_CALLS] Recording upload - call_id=#{call_id}, file present=#{recording_file.present?}, duration=#{duration_param}"

    return render json: { error: 'No recording file provided' }, status: :unprocessable_entity if recording_file.blank?

    whatsapp_call = WhatsappCall.find_by(call_id: call_id, account: Current.account)

    unless whatsapp_call
      Rails.logger.warn "[WHATSAPP_CALLS] WhatsappCall record not found for call_id=#{call_id}"
      return render json: { error: 'Call not found' }, status: :not_found
    end

    recording_path = save_recording_file(whatsapp_call, recording_file)

    # Use duration from params (frontend) or fallback to existing duration_seconds
    final_duration = duration_param.present? ? duration_param.to_i : (whatsapp_call.duration_seconds || 0)

    whatsapp_call.update!(
      recording_url: recording_path,
      duration_seconds: final_duration
    )

    create_recording_message(whatsapp_call, recording_path)

    Rails.logger.info "[WHATSAPP_CALLS] Recording saved successfully: #{recording_path}"

    render json: {
      message: 'Recording uploaded successfully',
      recording_path: recording_path
    }, status: :ok
  rescue StandardError => e
    Rails.logger.error "[WHATSAPP_CALLS] Failed to save recording: #{e.message}"
    Rails.logger.error e.backtrace.join("\n")
    render json: { error: 'Failed to save recording' }, status: :internal_server_error
  end

  def format_duration(seconds)
    return '0:00' unless seconds&.positive?

    minutes = seconds / 60
    secs = seconds % 60
    "#{minutes}:#{secs.to_s.rjust(2, '0')}"
  end

  def handle_webrtc_setup_error(conversation, call_id, error_message)
    Rails.logger.info '[WHATSAPP_CALLS] ===== handle_webrtc_setup_error STARTED ====='
    Rails.logger.info "[WHATSAPP_CALLS] Updating initiated message to error status for call_id=#{call_id}"
    Rails.logger.info "[WHATSAPP_CALLS] Conversation ID: #{conversation.id}"
    Rails.logger.info "[WHATSAPP_CALLS] Error message: #{error_message}"

    # Extract error code and message from WhatsApp API error
    error_text = error_message.to_s
    error_code = nil

    # Try to extract error code or classify error type
    if error_text =~ /Error code (\d+):/i
      error_code = ::Regexp.last_match(1)
    elsif /No approved call permission/i.match?(error_text)
      error_code = 'NO_CALL_PERMISSION'
    end

    Rails.logger.info "[WHATSAPP_CALLS] Extracted error_code: #{error_code}"

    # Find the "Call initiated..." message by specific call_id
    Rails.logger.info "[WHATSAPP_CALLS] Searching for message with call_id: #{call_id}"
    initiated_message = conversation.messages
                                    .where(message_type: :activity, content_type: :voice_call)
                                    .where("call_metadata->>'call_id' = ?", call_id)
                                    .where(call_status: :call_initiated)
                                    .first

    Rails.logger.info "[WHATSAPP_CALLS] Message found: #{initiated_message.present?}"

    if initiated_message
      Rails.logger.info "[WHATSAPP_CALLS] Found initiated message (id=#{initiated_message.id}), updating to error status"

      # Determine the appropriate error status
      error_status = Message::WhatsappCallMessage.meta_error_to_call_status(error_code, error_text)

      Rails.logger.info "[WHATSAPP_CALLS] Determined error_status: #{error_status}"

      # Get the status message
      status_message = case error_status
                       when :call_error_recipient_not_approved
                         '⚠️ Error: Recipient has not approved receiving calls'
                       when :call_error_unauthorized
                         '⚠️ Error: Not authorized for calling'
                       when :call_error_no_balance
                         '⚠️ Error: Insufficient balance'
                       when :call_error_not_enabled
                         '⚠️ Error: Calling not enabled'
                       when :call_error_rate_limit
                         '⚠️ Error: Rate limit exceeded'
                       when :call_error_invalid
                         '⚠️ Error: Invalid parameters'
                       else
                         '⚠️ Call failed'
                       end

      Rails.logger.info "[WHATSAPP_CALLS] Status message: #{status_message}"

      # Update the existing message to error status
      Rails.logger.info "[WHATSAPP_CALLS] Before update - call_status: #{initiated_message.call_status}, content: #{initiated_message.content}"

      initiated_message.call_status = error_status
      initiated_message.content = status_message
      initiated_message.call_metadata = (initiated_message.call_metadata || {}).merge(
        ended_at: Time.current.to_i,
        error_code: error_code || 'UNKNOWN',
        error_message: error_text
      )

      Rails.logger.info "[WHATSAPP_CALLS] After assignment - call_status: #{initiated_message.call_status}, content: #{initiated_message.content}"

      # Save and get changes before they're cleared
      initiated_message.save!
      changes = initiated_message.previous_changes

      Rails.logger.info '[WHATSAPP_CALLS] Message saved successfully'
      Rails.logger.info "[WHATSAPP_CALLS] Previous changes: #{changes.inspect}"
      Rails.logger.info "[WHATSAPP_CALLS] Message updated to #{error_status} status"

      # Manually dispatch the update event with the changes
      Rails.logger.info '[WHATSAPP_CALLS] Dispatching message.updated event...'
      Rails.configuration.dispatcher.dispatch(
        'message.updated',
        Time.zone.now,
        message: initiated_message,
        performed_by: nil,
        previous_changes: changes
      )
      Rails.logger.info '[WHATSAPP_CALLS] Event dispatched successfully'
      Rails.logger.info '[WHATSAPP_CALLS] ===== handle_webrtc_setup_error COMPLETED ====='
    else
      Rails.logger.warn "[WHATSAPP_CALLS] No initiated message found for call_id=#{call_id}"

      # Fallback: create new error message if initiated message not found
      whatsapp_call = WhatsappCall.new(
        account: Current.account,
        conversation: conversation,
        contact: conversation.contact,
        inbox: conversation.inbox,
        initiated_by_user: current_user,
        call_id: call_id || "error-#{SecureRandom.hex(8)}",
        direction: 'outbound',
        initiated_at: Time.current,
        status: 'failed'
      )

      Whatsapp::Calling::CallMessageBuilder.new(
        conversation: conversation,
        whatsapp_call: whatsapp_call
      ).create_meta_error_message(
        error_code: error_code || 'UNKNOWN',
        error_message: error_text,
        meta_response: nil
      )
    end

    Rails.logger.info '[WHATSAPP_CALLS] Error handling completed'
  rescue StandardError => e
    Rails.logger.error "[WHATSAPP_CALLS] Failed to handle setup error: #{e.message}"
    Rails.logger.error e.backtrace.first(5).join("\n")
  end
